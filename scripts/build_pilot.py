def dump(path, obj):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def main():
    assert len(ROWS) == 100
    records, authoring = [], []
    for i, row in enumerate(ROWS, 1):
        sid = f"Q{i:03d}"
        history = [dict(turn_id=f"{sid}-H{j}", user=q, assistant=a, provenance="synthetic_mock_context") for j, (q, a) in enumerate(row["history"], 1)]
        attachments = [] if row["attachment"] is None else [dict(attachment_id=f"{sid}-A1", provenance="synthetic_fixture", **row["attachment"])]
        records.append({
            "sample_id": sid, "conversation_id": f"SYN-{i:03d}", "scenario_group_id": f"SYN-{i:03d}",
            "source": {"kind": "synthetic", "created_on": "2026-09-21", "generator": "Codex assistant: individually authored synthetic fixtures", "is_real_baixiaoyi_traffic": False},
            "surface": "unspecified", "history": history,
            "history_info": {"available_rounds": len(history), "earlier_history_available": False, "earlier_history_status": "not_supplied"},
            "current": {"turn_id": f"{sid}-T{len(history)+1}", "query": row["query"], "answer": None, "answer_source": None},
            "attachments": attachments, "relevant_memory": [],
            "execution": {"observation_status": "not_collected", "events": []},
            "review": {"status": "pending_human_review", "clinical_accuracy": "not_evaluated", "gold_labels": None},
        })
        authoring.append({"sample_id": sid, "sampling_bucket": row["group"], "coverage_features": row["features"], "not_gold_labels": True, "never_include_in_jev_state": True})
    (ROOT / "data").mkdir(exist_ok=True)
    for name, data in [("query-pilot-100.jsonl", records), ("query-pilot-100.authoring.jsonl", authoring)]:
        (ROOT / "data" / name).write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in data), encoding="utf-8")
    counts = Counter(len(r["history"]) for r in records)
